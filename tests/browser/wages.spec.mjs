import { test, expect } from '@playwright/test'

const ordersRoute = '/admin/settings/compensation/wage-orders'
const adjustmentsRoute = '/admin/payroll/wage-adjustments'
const dialog = page => page.locator('dialog[open]')
const rows = page => page.locator('.page-content .table-card tbody tr')
const rowFor = (page, text) => rows(page).filter({ hasText: text }).first()
async function action(page, row, name) {
  await row.locator('.wage-action-trigger').click()
  await page.getByRole('menuitem', { name, exact: true }).click()
}
async function generate(page) {
  await page.getByRole('button', { name: 'Evaluate Employees', exact: true }).click()
  await expect(dialog(page)).toBeVisible()
  await dialog(page).getByRole('button', { name: 'Generate Proposals', exact: true }).click()
  await expect(dialog(page)).toHaveCount(0)
}
async function submit(page) {
  await page.getByRole('button', { name: 'Submit Batch for Approval', exact: true }).click()
  await dialog(page).getByRole('button', { name: 'Confirm Batch Submission', exact: true }).click()
}
async function approve(page, note = 'Required proposals verified for this sample evaluation.') {
  await page.getByRole('button', { name: 'Review Batch', exact: true }).click()
  await dialog(page).getByLabel('Approver Remarks', { exact: true }).fill(note)
  await dialog(page).getByRole('button', { name: 'Approve Batch', exact: true }).click()
}
test.beforeEach(async ({ page }) => {
  await page.addInitScript(() => {
    sessionStorage.setItem('rworkcentral-auth', '1')
    sessionStorage.setItem('rworkcentral-token', 'wage-flow-test')
    sessionStorage.setItem('rworkcentral-user', JSON.stringify({ id: 1, name: 'Batch Reviewer', role: 'admin' }))
    localStorage.setItem('hris-theme', 'dark')
  })
  await page.setViewportSize({ width: 1500, height: 1000 })
})

test('orders link only selects context; evaluation creates distinct result and workflow statuses', async ({ page }, testInfo) => {
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  await page.goto(ordersRoute)
  await rowFor(page, 'NCR-WO-2026-01').locator('.wage-action-trigger').click()
  await expect(page.getByRole('menuitem', { name: 'Evaluate Employees', exact: true })).toHaveCount(0)
  await page.getByRole('menuitem', { name: 'View Affected Employees', exact: true }).click()
  await expect(page).toHaveURL(/wage-adjustments\?order=/)
  await expect(dialog(page)).toHaveCount(0)
  await expect(page.getByLabel('Wage order filter')).toHaveValue('NCR-WO-2026-01')
  await generate(page)
  await expect(rows(page)).toHaveCount(8)
  const monthly = rowFor(page, 'Angela Flores')
  await expect(monthly).toContainText('monthly')
  await expect(monthly).toContainText('690.10')
  await expect(monthly).toContainText('Required')
  await expect(monthly).toContainText('Draft')
  await monthly.locator('.wage-action-trigger').click()
  await expect(page.getByRole('menuitem')).toHaveCount(2)
  await expect(page.getByRole('menuitem', { name: 'View Details', exact: true })).toBeVisible()
  await expect(page.getByRole('menuitem', { name: 'View History', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await page.screenshot({ path: testInfo.outputPath('01-evaluated-proposals.png'), fullPage: true })
  expect(errors).toEqual([])
})

test('one batch decision covers all Required rows even when table filters hide employees', async ({ page }, testInfo) => {
  await page.goto(adjustmentsRoute); await generate(page)
  await page.getByPlaceholder('Search employee or department...').fill('Juan Dela Cruz')
  await expect(rows(page)).toHaveCount(1)
  await page.getByRole('button', { name: 'Submit Batch for Approval', exact: true }).click()
  await expect(dialog(page).locator('table').first().locator('tbody tr')).toHaveCount(4)
  await dialog(page).getByRole('button', { name: 'Confirm Batch Submission', exact: true }).click()
  await expect(page.locator('.batch-card')).toContainText('For Review')
  await expect(page.getByLabel('Company Annual Factor', { exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Review Batch', exact: true }).click()
  await dialog(page).getByRole('button', { name: 'Reject Batch', exact: true }).click()
  await expect(dialog(page).getByRole('alert')).toContainText('remarks')
  await dialog(page).getByLabel('Approver Remarks', { exact: true }).fill('Please verify source and attendance.')
  await dialog(page).getByRole('button', { name: 'Reject Batch', exact: true }).click()
  await expect(page.locator('.batch-card')).toContainText('Rejected')
  await expect(rowFor(page, 'Juan Dela Cruz')).toContainText('Draft')
  await submit(page); await approve(page)
  await page.getByRole('button', { name: 'Apply Approved Adjustments', exact: true }).click()
  const preview = dialog(page)
  await expect(preview.locator('table').first().locator('tbody tr')).toHaveCount(4)
  await expect(preview).toContainText('Wage Order Retro Pay')
  await expect(preview).toContainText('13th-month basic-salary')
  await expect(preview.getByRole('button', { name: 'Confirm Application', exact: true })).toBeDisabled()
  await preview.getByRole('checkbox').check()
  await page.screenshot({ path: testInfo.outputPath('02-batch-retro-preview.png') })
  await preview.getByRole('button', { name: 'Confirm Application', exact: true }).click()
  await expect(page.locator('.batch-card')).toContainText('Applied')
  await expect(rowFor(page, 'Juan Dela Cruz')).toContainText('Required')
  await expect(rowFor(page, 'Juan Dela Cruz')).toContainText('Applied (Effective)')
  await page.getByRole('button', { name: 'Reset', exact: true }).click()
  await expect(rowFor(page, 'Angela Flores')).toContainText('Applied (Effective)')
  await expect(rowFor(page, 'Jenny Ramos')).toContainText('Draft')
  await expect(page.getByRole('button', { name: 'Apply Approved Adjustments', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Batch History', exact: true }).click()
  await expect(dialog(page)).toContainText('Batch Rejected')
  await expect(dialog(page)).toContainText('Batch Applied')
  await expect(dialog(page)).toContainText('Batch Reviewer')
})

test('future scheduled order can be approved but Apply remains disabled with no retro', async ({ page }) => {
  await page.goto(adjustmentsRoute + '?order=NCR-WO-2026-01-T2')
  await expect(dialog(page)).toHaveCount(0)
  await generate(page); await submit(page); await approve(page)
  const apply = page.getByRole('button', { name: 'Apply Approved Adjustments', exact: true })
  await expect(apply).toBeDisabled()
  await expect(apply).toHaveAttribute('title', /disabled until 2027-01-01/)
  await expect(rowFor(page, 'Juan Dela Cruz')).toContainText('Scheduled')
  await action(page, rowFor(page, 'Juan Dela Cruz'), 'View Details')
  await expect(dialog(page)).toContainText('No retro')
  await expect(dialog(page)).toContainText('720.00')
})

test('HR distortion decisions are individual and never enter the Required batch', async ({ page }) => {
  await page.goto(adjustmentsRoute); await generate(page)
  await action(page, rowFor(page, 'Pedro Reyes'), 'Review Proposal')
  await dialog(page).getByRole('button', { name: 'Dismiss Case', exact: true }).click()
  await expect(dialog(page).getByRole('alert')).toContainText('remarks')
  await dialog(page).getByLabel('HR Decision Remarks', { exact: true }).fill('No correction required after HR review.')
  await dialog(page).getByRole('button', { name: 'Dismiss Case', exact: true }).click()
  await expect(rowFor(page, 'Pedro Reyes')).toContainText('Dismissed')
  await action(page, rowFor(page, 'Jenny Ramos'), 'Review Proposal')
  await dialog(page).getByLabel('Proposed Daily Rate (PHP)', { exact: true }).fill('780')
  await dialog(page).getByLabel('HR Decision Remarks', { exact: true }).fill('Approved senior role alignment.')
  await dialog(page).getByRole('button', { name: 'Approve HR Correction', exact: true }).click()
  await action(page, rowFor(page, 'Jenny Ramos'), 'Apply HR Correction')
  await expect(dialog(page)).toContainText('separately approved HR correction')
  await dialog(page).getByRole('checkbox').check()
  await dialog(page).getByRole('button', { name: 'Confirm Application', exact: true }).click()
  await expect(rowFor(page, 'Jenny Ramos')).toContainText('Applied (Effective)')
  await expect(page.locator('.batch-card')).toContainText('Draft')
  await page.getByRole('button', { name: 'Submit Batch for Approval', exact: true }).click()
  await expect(dialog(page)).not.toContainText('Jenny Ramos')
  await expect(dialog(page)).not.toContainText('Pedro Reyes')
})

test('annual factor and distortion threshold are configurable and invalidate unsubmitted evaluations', async ({ page }) => {
  await page.goto(adjustmentsRoute); await generate(page)
  await expect(rowFor(page, 'Angela Flores')).toContainText('Required')
  await page.getByLabel('Company Annual Factor', { exact: true }).fill('261')
  await page.getByLabel('Distortion Threshold', { exact: true }).fill('0')
  await page.getByRole('button', { name: 'Save Evaluation Rules', exact: true }).click()
  await expect(page.locator('.batch-card')).toContainText('Not evaluated')
  await generate(page)
  await expect(rowFor(page, 'Angela Flores')).toContainText('827.59')
  await expect(rowFor(page, 'Angela Flores')).toContainText('Compliant')
  await expect(rowFor(page, 'Jenny Ramos')).toContainText('Compliant')
})

test('wage order form uses a region dropdown and read-only preceding tranche minimum', async ({ page }) => {
  await page.goto(ordersRoute)
  await page.getByRole('button', { name: 'Add Wage Order', exact: true }).click()
  const form = dialog(page)
  await form.getByLabel('Region', { exact: true }).selectOption('NCR')
  await form.getByLabel('Effective Date', { exact: true }).fill('2027-02-01')
  await expect(form.getByLabel('Previous Daily Minimum (PHP)', { exact: true })).toHaveValue('780')
  await expect(form.getByLabel('Previous Daily Minimum (PHP)', { exact: true })).toHaveAttribute('readonly', '')
  await form.getByLabel('Order Code', { exact: true }).fill('UI-TRANCHE-03')
  await form.getByLabel('Title', { exact: true }).fill('Third sample tranche')
  await form.getByLabel('New Daily Minimum (PHP)', { exact: true }).fill('780')
  await form.getByRole('button', { name: 'Save Draft', exact: true }).click()
  await expect(form.getByRole('alert')).toContainText('greater')
  await form.getByLabel('Effective Date', { exact: true }).fill('2027-01-01')
  await form.getByLabel('New Daily Minimum (PHP)', { exact: true }).fill('800')
  await form.getByRole('button', { name: 'Save Draft', exact: true }).click()
  await expect(form.getByRole('alert')).toContainText('effective date')
  await form.getByLabel('Effective Date', { exact: true }).fill('2027-02-01')
  await form.getByRole('button', { name: 'Save Draft', exact: true }).click()
  const row = rowFor(page, 'UI-TRANCHE-03')
  await expect(row).toContainText('Draft')
  await action(page, row, 'Schedule Order')
  await dialog(page).getByRole('button', { name: 'Schedule Wage Order', exact: true }).click()
  await expect(row).toContainText('Scheduled')
})

test('no-required empty state disables batch submission; first-order minimum permits manual input', async ({ page }) => {
  await page.goto(ordersRoute)
  await page.getByRole('button', { name: 'Add Wage Order', exact: true }).click()
  const form = dialog(page)
  await form.getByLabel('Order Code', { exact: true }).fill('UI-OLD-SAMPLE')
  await form.getByLabel('Title', { exact: true }).fill('Earlier sample baseline')
  await form.getByLabel('Effective Date', { exact: true }).fill('2026-01-02')
  await expect(form.getByLabel('Previous Daily Minimum (PHP)', { exact: true })).not.toHaveAttribute('readonly')
  await form.getByLabel('Previous Daily Minimum (PHP)', { exact: true }).fill('640')
  await form.getByLabel('New Daily Minimum (PHP)', { exact: true }).fill('650')
  await form.getByRole('button', { name: 'Save Draft', exact: true }).click()
  await action(page, rowFor(page, 'UI-OLD-SAMPLE'), 'Activate Order')
  await dialog(page).getByRole('button', { name: 'Activate Wage Order', exact: true }).click()
  await action(page, rowFor(page, 'UI-OLD-SAMPLE'), 'View Affected Employees')
  await generate(page)
  await expect(page.locator('.demo-notice').filter({ hasText: 'No employees below the new minimum.' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Submit Batch for Approval', exact: true })).toBeDisabled()
})
