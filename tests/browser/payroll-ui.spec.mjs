import { test, expect } from '@playwright/test'
import fs from 'node:fs/promises'
import ExcelJS from 'exceljs'

const modal = page => page.locator('dialog[open]')
test.beforeEach(async ({ page }) => {
  await page.addInitScript(() => {
    sessionStorage.setItem('rworkcentral-auth', '1')
    sessionStorage.setItem('rworkcentral-token', 'payroll-ui-test')
    sessionStorage.setItem('rworkcentral-user', JSON.stringify({ id: 1, name: 'Payroll UI Tester', role: 'admin' }))
    localStorage.setItem('hris-theme', 'dark')
  })
  await page.setViewportSize({ width: 1500, height: 1000 })
})
const routes = ['/admin/rates', '/admin/loans', '/admin/payroll', '/admin/pending-employees-payroll', '/admin/completed-employees-payroll', '/admin/employee-payroll', '/admin/payroll/payroll-group']
for (const route of routes) {
  test(`${route}: missing export UI downloads current filtered data`, async ({ page }) => {
    const errors = []; page.on('pageerror', error => errors.push(error.message))
    await page.goto(route)
    await page.getByRole('button', { name: 'Export', exact: true }).click()
    await expect(modal(page)).toContainText('records selected')
    await modal(page).getByLabel('File Format', { exact: true }).selectOption('CSV')
    const event = page.waitForEvent('download')
    await modal(page).getByRole('button', { name: 'Download CSV', exact: true }).click()
    const download = await event
    expect(download.suggestedFilename()).toMatch(/\.csv$/)
    const csv = await fs.readFile(await download.path(), 'utf8')
    expect(csv).toContain('Sample data')
    expect(csv.length).toBeGreaterThan(150)
    await modal(page).getByRole('button', { name: 'Close', exact: true }).click()
    expect(errors).toEqual([])
  })
}

