  // Methods to mutate/manage policies
  const togglePolicyStatus = (policyId: number) => {
    const policy = policies.value.find(p => p.id === policyId)
    if (policy) {
      policy.status = !policy.status
    }
  }

  const savePolicy = (data: Partial<LifecyclePolicy>) => {
    if (data.id) {
      const idx = policies.value.findIndex(p => p.id === data.id)
      if (idx !== -1) {
        policies.value[idx] = {
          ...policies.value[idx],
          ...data,
          updatedAt: new Date().toISOString().slice(0, 10),
        }
      }
    } else {
      const newId = Math.max(0, ...policies.value.map(p => p.id)) + 1
      policies.value.push({
        id: newId,
        name: data.name || 'Untitled Policy',
        description: data.description || '',
        employmentTypeId: data.employmentTypeId ?? null,
        employmentTypeName: data.employmentTypeName || 'All Types',
        userId: 1,
        creatorName: 'HR Administrator',
        status: data.status ?? true,
        stagesCount: 0,
        createdAt: new Date().toISOString().slice(0, 10),
        updatedAt: new Date().toISOString().slice(0, 10),
      })
    }
  }

  const deletePolicy = (policyId: number) => {
    policies.value = policies.value.filter(p => p.id !== policyId)
    stages.value = stages.value.filter(s => s.lifecyclePolicyId !== policyId)
  }

  // Methods to mutate/manage stages
  const toggleStageStatus = (stageId: number) => {
    const stage = stages.value.find(s => s.id === stageId)
    if (stage) {
      stage.status = !stage.status
    }
  }

  const saveStage = (data: Partial<LifecycleStage>) => {
    if (data.id) {
      const idx = stages.value.findIndex(s => s.id === data.id)
      if (idx !== -1) {
        stages.value[idx] = {
          ...stages.value[idx],
          ...data,
        }
      }
    } else {
      const newId = Math.max(0, ...stages.value.map(s => s.id)) + 1
      const policy = policies.value.find(p => p.id === data.lifecyclePolicyId)
      stages.value.push({
        id: newId,
        lifecyclePolicyId: data.lifecyclePolicyId || 1,
        policyName: policy ? policy.name : 'Unknown Policy',
        stageName: data.stageName || 'New Stage',
        stageCode: data.stageCode || `STAGE_${newId}`,
        monthsAfterHire: Number(data.monthsAfterHire) || 1,
        sortOrder: Number(data.sortOrder) || stages.value.length + 1,
        status: data.status ?? true,
        milestonesCount: 0,
      })
      if (policy) policy.stagesCount++
    }
  }

  const deleteStage = (stageId: number) => {
    const stage = stages.value.find(s => s.id === stageId)
    if (stage) {
      const policy = policies.value.find(p => p.id === stage.lifecyclePolicyId)
      if (policy && policy.stagesCount > 0) policy.stagesCount--
    }
    stages.value = stages.value.filter(s => s.id !== stageId)
  }

  // Methods to mutate/manage milestones based on evaluation attachment
  const attachEvaluationFile = (
    milestoneId: number,
    fileName: string,
    fileSize = '1.2 MB',
    remarks?: string,
    triggerRegularize = true,
  ) => {
    const milestone = milestones.value.find(m => m.id === milestoneId)
    if (milestone) {
      milestone.attachmentName = fileName
      milestone.attachmentSize = fileSize
      milestone.attachedAt = new Date().toISOString().slice(0, 10)
      milestone.status = 'completed' // Status automatically changes to Completed when evaluation proof is attached
      if (remarks !== undefined) {
        milestone.remarks = remarks
      }

      // If this milestone is the 6th Month Regularization Milestone, trigger employmentType upgrade to Regular
      if (milestone.stageCode === 'M6_REGULARIZATION' && triggerRegularize) {
        const empId = milestone.employeeId
        milestones.value.forEach(m => {
          if (m.employeeId === empId) {
            m.employmentType = 'Regular'
          }
        })
      }
    }
  }

  const removeEvaluationFile = (milestoneId: number) => {
    const milestone = milestones.value.find(m => m.id === milestoneId)
    if (milestone) {
      milestone.attachmentName = null
      milestone.attachmentSize = null
      milestone.attachedAt = null
      milestone.status = 'pending' // Status reverts to Pending when attachment is removed

      // If removed on 6th Month Regularization Milestone, revert back to Probationary
      if (milestone.stageCode === 'M6_REGULARIZATION') {
        const empId = milestone.employeeId
        milestones.value.forEach(m => {
          if (m.employeeId === empId) {
            m.employmentType = 'Probationary'
          }
        })
      }
    }
  }

  const updateMilestoneRemarks = (milestoneId: number, remarks: string) => {
    const milestone = milestones.value.find(m => m.id === milestoneId)
    if (milestone) {
      milestone.remarks = remarks
    }
  }

  return {
    policies,
    stages,
    milestones,
    togglePolicyStatus,
    savePolicy,
    deletePolicy,
    toggleStageStatus,
    saveStage,
    deleteStage,
    attachEvaluationFile,
    removeEvaluationFile,
    updateMilestoneRemarks,
  }
